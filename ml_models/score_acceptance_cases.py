"""score_acceptance_cases.py — produce the committee-facing SAMPLE RUNS pack.

Given a cases spec (JSON: dataset, selected columns, governance config, product
policy, and a set of named candidate applicants), scores each candidate through
the AEGIS-approved model + policy and writes a markdown pack showing, per
candidate, exactly how a new applicant's information is showcased before the
Go/No-Go decision: inputs, raw -> calibrated PD (floored), rating grade, the
policy decision + indicative rate, the full exact reason-code decomposition, and
the principal (adverse-action) reasons.

This is a REQUIRED pre-GF deliverable: the Model Approval Committee reviews the
pack (SAMPLE_RUNS_<DATASET>.md) to see the model's behaviour on concrete cases
before ruling. Inputs live in acceptance_cases/<dataset>.json so the sample runs
are reproducible, not one-off.

Usage:
  python ml_models/score_acceptance_cases.py --cases "paper analysis/draft one/acceptance_cases/hmeq.json" \
      --out "paper analysis/draft one/SAMPLE_RUNS_HMEQ.md"
"""
import sys, os, json, argparse, warnings
import numpy as np, pandas as pd
warnings.simplefilter('ignore')
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(ROOT, 'backend'))
import missing_governance as mg
try:
    import rating_masterscale as rm
except Exception:
    sys.path.insert(0, os.path.join(ROOT, 'backend')); import rating_masterscale as rm


def band(pd_value, pol):
    LGD, C, M = pol['LGD'], pol['cost'], pol['margin']
    rate = min(C + pd_value * LGD + M, pol['max_rate'])
    approve_std = (pol['std_rate'] - C - M) / LGD
    decline = (pol['max_rate'] - C - M) / LGD
    if pd_value <= approve_std:        dec = pol.get('label_approve_std', 'APPROVE (standard)')
    elif pd_value <= pol['refer_floor']: dec = pol.get('label_approve_rb', 'APPROVE (risk-based)')
    elif pd_value <= decline:          dec = pol.get('label_refer', 'REFER (manual)')
    else:                              dec = pol.get('label_decline', 'DECLINE')
    return dec, rate, approve_std, decline


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cases', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    spec = json.load(open(a.cases, encoding='utf-8'))
    df = pd.read_csv(os.path.join(ROOT, 'data', 'ml_lab', 'datasets', spec['dataset']))
    target = spec.get('target', 'target'); SEL = spec['selected_columns']
    port = float(df[target].mean())
    scorer, _ = mg.build_scorer(df, target, SEL,
                                mandatory_columns=spec.get('mandatory_columns', []),
                                floor_columns=spec.get('floor_columns', []),
                                incomplete_policy=spec.get('incomplete_policy', 'refer'),
                                random_state=42)
    enc, coef, intercept, iso, order = (scorer.encoder, scorer.coef, scorer.intercept,
                                        scorer.iso, scorer.columns)
    pol = spec['policy']
    L = ['# SAMPLE RUNS — %s' % spec.get('title', spec['dataset']),
         '',
         '**Committee-facing acceptance pack (reviewed BEFORE the Go/No-Go decision).** Generated by '
         '`ml_models/score_acceptance_cases.py` from `%s` — reproducible, not one-off.' % os.path.basename(a.cases),
         '',
         '**Model:** AEGIS-approved WOE-logistic (%d features) · **Portfolio default rate:** %.1f%% · '
         'PD floored at %.2f%% (Basel CRE32.3).' % (len(order), 100*port, 100*scorer.pd_floor),
         '', '## Summary', '',
         '| Candidate | Calibrated PD | Grade | Decision | Indic. rate | Principal reasons |',
         '|---|--:|---|---|--:|---|']
    details = []
    for name, cust in spec['cases'].items():
        row = pd.DataFrame([cust]).reindex(columns=order)
        W = enc.transform(scorer._prep(row)).values.astype(float)[0]
        contrib = coef * W
        gov = scorer.score(row).iloc[0]
        raw = 1.0 / (1.0 + np.exp(-(intercept + contrib.sum())))
        pd_ = float(gov['probability'])
        g = rm.pd_to_grade(pd_); dec, rate, astd, dcl = band(pd_, pol)
        t = pd.DataFrame({'feature': order, 'value': [cust[c] for c in order],
                          'WOE': np.round(W, 3), 'contribution': np.round(contrib, 3)})
        t['effect'] = np.where(t.contribution > 0, 'raises risk', 'lowers risk')
        t = t.reindex(t.contribution.abs().sort_values(ascending=False).index)
        adv = t[t.contribution > 0].head(3).feature.tolist()
        L.append('| **%s** | %.2f%% | %s | %s | %.1f%% | %s |'
                 % (name, 100*pd_, g['grade'], dec, 100*rate, ', '.join(adv) if adv else 'all protective'))
        d = ['', '### %s' % name, '',
             '**Inputs:** ' + ', '.join('%s=%s' % (c, cust[c]) for c in order), '',
             '**Governed decision:** %s · raw PD %.2f%% → **calibrated PD %.2f%%** (%.2f× portfolio) · '
             'grade **%s** (%s) · **%s** · indicative rate %.1f%%'
             % (gov['decision'], 100*raw, 100*pd_, pd_/port, g['grade'], g['label'], dec, 100*rate),
             '']
        if gov['reason']:
            d.append('Governance note: %s' % gov['reason']); d.append('')
        d.append('| Feature | Value | WOE | Contribution | Effect |')
        d.append('|---|---|--:|--:|---|')
        for _, r in t.iterrows():
            d.append('| %s | %s | %+.3f | %+.3f | %s |' % (r.feature, r.value, r.WOE, r.contribution, r.effect))
        d.append('')
        d.append('**Principal (adverse-action) reasons:** ' + (', '.join(adv) if adv else 'none — all factors protective'))
        details.append('\n'.join(d))
    L.append('')
    L.append('Policy bands (fixed, absolute PD): approve-standard ≤ %.1f%% · refer > %.1f%% · decline > %.1f%% '
             '(illustrative economics — Risk Committee ratifies).' % (100*astd, 100*pol['refer_floor'], 100*dcl))
    L.append('')
    L.append('---')
    L.append('## Per-candidate showcase (what a new applicant report looks like)')
    L.extend(details)
    open(a.out, 'w', encoding='utf-8').write('\n'.join(L))
    print('WROTE', a.out, '(%d candidates)' % len(spec['cases']))


if __name__ == '__main__':
    main()
